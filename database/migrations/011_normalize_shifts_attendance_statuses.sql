-- Normalize shift/session relationships and database lifecycle constraints.
SET search_path TO sigma_presensi;

DO $$
BEGIN
  CREATE TYPE record_status AS ENUM ('Aktif', 'Non Aktif');
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;

CREATE TABLE IF NOT EXISTS shifts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  nama_shift VARCHAR(250) NOT NULL,
  staff_user_id BIGINT NOT NULL,
  location_id BIGINT NOT NULL,
  start_shift TIME NOT NULL,
  end_shift TIME NOT NULL,
  status record_status NOT NULL DEFAULT 'Aktif',
  created_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  deleted_at TIMESTAMPTZ(6) NULL,
  PRIMARY KEY (id),
  CONSTRAINT fk_shifts_staff FOREIGN KEY (staff_user_id) REFERENCES users (id),
  CONSTRAINT fk_shifts_location FOREIGN KEY (location_id) REFERENCES location (id),
  CONSTRAINT shifts_time_check CHECK (end_shift > start_shift)
);

CREATE TABLE IF NOT EXISTS shift_participants (
  shift_id BIGINT NOT NULL,
  participant_user_id BIGINT NOT NULL,
  created_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  PRIMARY KEY (shift_id, participant_user_id),
  CONSTRAINT fk_shift_participants_shift FOREIGN KEY (shift_id) REFERENCES shifts (id),
  CONSTRAINT fk_shift_participants_user FOREIGN KEY (participant_user_id) REFERENCES users (id)
);

ALTER TABLE work_sessions ADD COLUMN IF NOT EXISTS shift_id BIGINT;
ALTER TABLE work_sessions ADD COLUMN IF NOT EXISTS participant_user_id BIGINT;

DO $$
