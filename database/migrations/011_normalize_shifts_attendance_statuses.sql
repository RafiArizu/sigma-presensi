INSERT INTO shifts (nama_shift, staff_user_id, location_id, start_shift, end_shift, status)
SELECT DISTINCT ON (pl.id)
  'Shift Penempatan ' || pl.id,
  pl.staff_user_id,
  ws.location_id,
  CASE WHEN (ws.end_at_utc AT TIME ZONE ws.timezone)::time > (ws.start_at_utc AT TIME ZONE ws.timezone)::time
       THEN (ws.start_at_utc AT TIME ZONE ws.timezone)::time
       ELSE (ws.start_at_utc AT TIME ZONE 'UTC')::time END,
  CASE WHEN (ws.end_at_utc AT TIME ZONE ws.timezone)::time > (ws.start_at_utc AT TIME ZONE ws.timezone)::time
       THEN (ws.end_at_utc AT TIME ZONE ws.timezone)::time
       ELSE (ws.end_at_utc AT TIME ZONE 'UTC')::time END,
  'Aktif'
FROM work_sessions ws
JOIN placements pl ON pl.id = ws.placement_id
WHERE NOT EXISTS (
  SELECT 1 FROM shifts s WHERE s.nama_shift = 'Shift Penempatan ' || pl.id
)
ORDER BY pl.id, ws.id;

INSERT INTO shift_participants (shift_id, participant_user_id)
SELECT s.id, pl.participant_user_id
FROM shifts s
JOIN placements pl ON s.nama_shift = 'Shift Penempatan ' || pl.id
ON CONFLICT DO NOTHING;

UPDATE work_sessions ws
SET shift_id = s.id,
    participant_user_id = pl.participant_user_id
FROM placements pl
JOIN shifts s ON s.nama_shift = 'Shift Penempatan ' || pl.id
WHERE ws.placement_id = pl.id;

