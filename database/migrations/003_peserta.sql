-- Participant profile and soft-delete support.
SET search_path TO sigma_presensi;

ALTER TABLE users ADD COLUMN IF NOT EXISTS deleted_at TIMESTAMPTZ(6) NULL;

DO $$ BEGIN
  CREATE TYPE institut_pendidikan AS ENUM ('Sekolah', 'Perguruan Tinggi');
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;
DO $$ BEGIN
  CREATE TYPE jenis_prakerin AS ENUM ('PKL', 'Magang/Kerja Praktik');
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;

CREATE TABLE IF NOT EXISTS peserta (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  user_id BIGINT NOT NULL,
  nama_lengkap VARCHAR(150) NOT NULL,
  no_telp VARCHAR(32) NOT NULL,
  institut_pendidikan institut_pendidikan NOT NULL,
  jenis_prakerin jenis_prakerin NOT NULL,
  mulai_prakerin DATE NOT NULL,
  selesai_prakerin DATE NOT NULL,
  created_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  deleted_at TIMESTAMPTZ(6) NULL,
  PRIMARY KEY (id),
  CONSTRAINT uq_peserta_user_id UNIQUE (user_id),
  CONSTRAINT fk_peserta_user FOREIGN KEY (user_id) REFERENCES users (id),
  CONSTRAINT peserta_prakerin_dates_check CHECK (selesai_prakerin >= mulai_prakerin),
  CONSTRAINT peserta_institut_prakerin_check CHECK (
    (institut_pendidikan = 'Sekolah' AND jenis_prakerin = 'PKL') OR
    (institut_pendidikan = 'Perguruan Tinggi' AND jenis_prakerin = 'Magang/Kerja Praktik')
  )
);

CREATE INDEX IF NOT EXISTS idx_users_deleted_at ON users (deleted_at);
CREATE INDEX IF NOT EXISTS idx_peserta_deleted_at ON peserta (deleted_at);
